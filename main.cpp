#include <iostream>
using namespace std;

int main()
{
    // ============================
    // Задача Begin21
    // Переведення кута з радіанів у градуси
    // ============================

    cout << "===== Задача Begin21 =====" << endl;

    double alpha, degrees;

    // Введення кута в радіанах
    cout << "Введіть значення кута alpha в радіанах: ";
    cin >> alpha;

    // За умовою pi = 3.14
    // 180 градусів = pi радіанів
    degrees = alpha * 180 / 3.14;

    // Виведення результату
    cout << "Значення кута в градусах: " << degrees << endl;


    // ============================
    // Задача Begin17
    // Обчислення значення функції
    // ============================

    cout << "\n===== Задача Begin17 =====" << endl;

    double x, y;

    // Введення значення x
    cout << "Введіть значення x: ";
    cin >> x;

    // Обчислення функції:
    // y = 4(x-3)^6 - 7(x-3)^3 + 2
    y = 4 * (x - 3) * (x - 3) * (x - 3) *
        (x - 3) * (x - 3) * (x - 3)
        - 7 * (x - 3) * (x - 3) * (x - 3) + 2;

    // Виведення результату
    cout << "Значення функції y = " << y << endl;


    // ============================
    // Задача Begin36
    // Знаходження діаметра кола
    // ============================

    cout << "\n===== Задача Begin36 =====" << endl;

    double L, D;

    // Введення довжини кола
    cout << "Введіть довжину кола L: ";
    cin >> L;

    // За умовою pi = 3.14
    D = L / 3.14;

    // Виведення результату
    cout << "Діаметр кола D = " << D << endl;

    return 0;
}
